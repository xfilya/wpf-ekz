PRAGMA foreign_keys = ON;
CREATE TABLE categories (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name TEXT NOT NULL UNIQUE);
CREATE TABLE manufacturers (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name TEXT NOT NULL UNIQUE);
CREATE TABLE roles (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name TEXT NOT NULL UNIQUE);
CREATE TABLE users (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 login TEXT NOT NULL UNIQUE,
 first_name TEXT NOT NULL, last_name TEXT NOT NULL,
 patronymic TEXT NOT NULL, role_id INTEGER NOT NULL,
 FOREIGN KEY(role_id) REFERENCES roles(id)
  ON UPDATE CASCADE ON DELETE CASCADE);
CREATE TABLE products (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 name TEXT NOT NULL, category_id INTEGER NOT NULL,
 manufacturer_id INTEGER NOT NULL, description TEXT NOT NULL,
 composition TEXT NOT NULL, price REAL NOT NULL,
 image_file_name TEXT,
 FOREIGN KEY(category_id) REFERENCES categories(id)
  ON UPDATE CASCADE ON DELETE CASCADE,
 FOREIGN KEY(manufacturer_id) REFERENCES manufacturers(id)
  ON UPDATE CASCADE ON DELETE CASCADE);
CREATE TABLE stock_items (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 product_id INTEGER NOT NULL,
 quantity INTEGER NOT NULL, size REAL NOT NULL,
 FOREIGN KEY(product_id) REFERENCES products(id)
  ON UPDATE CASCADE ON DELETE CASCADE);
CREATE TABLE orders (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 order_date TEXT NOT NULL, user_id INTEGER NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
  ON UPDATE CASCADE ON DELETE CASCADE);
CREATE TABLE order_items (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 order_id INTEGER NOT NULL, stock_item_id INTEGER NOT NULL,
 quantity INTEGER NOT NULL, unit_price REAL NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id)
  ON UPDATE CASCADE ON DELETE CASCADE,
 FOREIGN KEY(stock_item_id) REFERENCES stock_items(id)
  ON UPDATE CASCADE ON DELETE CASCADE);
